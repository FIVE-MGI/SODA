def gene_table(rng):
    markers = [f"MARKER_{MARKER_TAG[t]}{k}" for t in MARKER_TAG for k in (1, 2)]
    plain = [f"GENE{i:03d}" for i in range(1, N_GENES - len(markers) + 1)]
    names = markers + plain
    ids = [f"DEMO{i:06d}" for i in range(1, N_GENES + 1)]
    base = rng.normal(0, 1.0, N_GENES)
    base[: len(markers)] = -2.5                      # markers are rare outside their region
    prog = np.zeros((len(REGIONS), N_GENES))
    plain_idx = np.arange(len(markers), N_GENES)
    for t in MARKER_TAG:
        up = rng.choice(plain_idx, 25, replace=False)
        prog[t, up] = rng.uniform(1.0, 2.4, 25)
        down = rng.choice(np.setdiff1d(plain_idx, up), 10, replace=False)
        prog[t, down] = -rng.uniform(0.8, 1.6, 10)
    prog[RIM] += 0.45 * prog[FASC]                   # related tissues share part of a program
    prog[EDGE] += 0.45 * prog[STROMA]
    prog[VESSEL] += 0.25 * prog[STROMA]
    for t in MARKER_TAG:                             # markers set last so the sharing above leaves them
        i = 2 * (t - 1)
        prog[:, i:i + 2] = 0
        prog[t, i:i + 2] = 5.0
    mu = np.exp(base[None, :] + prog)
    mu /= mu.sum(1, keepdims=True)
    mu[BG] = 0
    return names, ids, mu


def bin_fractions(n_bins, bin_um, sub=5):
    """Fraction of each region inside each square bin, from sub x sub sample points."""
    X, Y = _grid(n_bins * sub, bin_um / sub)
    lab = region_at(X, Y)
    oh = np.zeros((n_bins, n_bins, len(REGIONS)), np.float32)
    lab = lab.reshape(n_bins, sub, n_bins, sub)
    for t in range(len(REGIONS)):
        oh[..., t] = (lab == t).mean(axis=(1, 3))
    return oh


def write_h5(path: Path, counts: sparse.csr_matrix, barcodes, ids, names):
    """10x Genomics feature-barcode HDF5 (v3 layout): CSC by barcode."""
    B, G = counts.shape
    csr = counts.tocsr()                             # bins x genes CSR == genes x bins CSC
    csr.sort_indices()
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(str(path), "w") as f:
        f.attrs["filetype"] = "matrix"
        f.attrs["version"] = np.int64(2)
        f.attrs["software_version"] = "make_demo.py (SYNTHETIC)"
        f.attrs["chemistry_description"] = "SYNTHETIC demo - not a real run"
        f.attrs["library_ids"] = np.array([b"demo"])
        f.attrs["original_gem_groups"] = np.array([1], np.int64)
        f.attrs["synthetic_note"] = NOTE
        m = f.create_group("matrix")
        m.create_dataset("barcodes", data=np.array(barcodes, dtype="S"))
        m.create_dataset("data", data=csr.data.astype(np.int32), compression="gzip", shuffle=True)
        m.create_dataset("indices", data=csr.indices.astype(np.int64), compression="gzip", shuffle=True)
        m.create_dataset("indptr", data=csr.indptr.astype(np.int64), compression="gzip", shuffle=True)
        m.create_dataset("shape", data=np.array([G, B], np.int32))
        ft = m.create_group("features")
        ft.create_dataset("_all_tag_keys", data=np.array([b"genome"]))
        ft.create_dataset("feature_type", data=np.array([b"Gene Expression"] * G))
        ft.create_dataset("genome", data=np.array([b"SYNTHETIC"] * G))
        ft.create_dataset("id", data=np.array(ids, dtype="S"))
        ft.create_dataset("name", data=np.array(names, dtype="S"))


def write_layer(outs: Path, raw: Path, bin_um: int, counts_grid: np.ndarray, included: np.ndarray,
                truth: np.ndarray, ids, names):
    """One binned_outputs/square_XXXum folder from a (rows, cols, genes) count grid."""
    n = included.shape[0]
    step_px = bin_um / MPP
    tag = f"{bin_um:03d}um"
    rows, cols = np.mgrid[0:n, 0:n]
    rows, cols = rows.ravel(), cols.ravel()
    bcs = [f"s_{tag}_{r:05d}_{c:05d}-1" for r, c in zip(rows, cols)]
    inc = included.ravel()
    d = outs / "binned_outputs" / f"square_{tag}"
    (d / "spatial").mkdir(parents=True, exist_ok=True)

    # tissue_positions.parquet lists every bin of the grid, like Space Ranger
    schema = pa.schema([("barcode", pa.string()), ("in_tissue", pa.int32()), ("array_row", pa.int32()),
                        ("array_col", pa.int32()), ("pxl_row_in_fullres", pa.float64()),
                        ("pxl_col_in_fullres", pa.float64())],
                       metadata={b"synthetic_note": NOTE.encode()})
    t = pa.table({"barcode": bcs, "in_tissue": inc.astype(np.int32), "array_row": rows.astype(np.int32),
                  "array_col": cols.astype(np.int32), "pxl_row_in_fullres": (rows + 0.5) * step_px,
                  "pxl_col_in_fullres": (cols + 0.5) * step_px}, schema=schema)
    pq.write_table(t, str(d / "spatial" / "tissue_positions.parquet"))

    sf = {"spot_diameter_fullres": step_px, "bin_size_um": float(bin_um), "microns_per_pixel": MPP,
          "regist_target_img_scalef": 1.0, "tissue_hires_scalef": 0.15, "tissue_lowres_scalef": 0.05,
          "fiducial_diameter_fullres": step_px * 4, "synthetic_note": NOTE}
    (d / "spatial" / "scalefactors_json.json").write_text(json.dumps(sf, indent=2), encoding="utf-8")

    sel = np.flatnonzero(inc)
    X = sparse.csr_matrix(counts_grid.reshape(n * n, -1)[sel])
    write_h5(d / "filtered_feature_bc_matrix.h5", X, [bcs[i] for i in sel], ids, names)
    with open(raw / f"truth_square_{tag}.csv", "w", encoding="utf-8", newline="\n") as f:
        f.write("barcode,region\n")
        tr = truth.ravel()
        for i in sel:
            f.write(f"{bcs[i]},{REGIONS[tr[i]]}\n")
    umi = np.asarray(X.sum(1)).ravel()
    log(f"[demo] square_{tag}: {len(sel):,} bins under tissue (of {n * n:,}), {X.shape[1]} genes, "
        f"median {np.median(umi):.0f} UMI, {(umi < 10).mean() * 100:.1f}% < 10 UMI, nnz {X.nnz:,}")


def make_visium(rng, raw: Path):
    t0 = time.time()
    names, ids, mu = gene_table(rng)
    n8 = int(round(FIELD_UM / 8))                    # 160 x 160 bins of 8 um
    frac = bin_fractions(n8, 8.0)                    # (160, 160, regions)
    tissue = 1 - frac[..., BG]
    inc8 = tissue >= 0.5
    w = frac[..., 1:] / np.maximum(tissue, 1e-6)[..., None]          # mix of tissue regions
    p = np.einsum("rck,kg->rcg", w, mu[1:]).astype(np.float32)
    logd = np.log(np.array([DEPTH[t] for t in range(1, len(REGIONS))], np.float32))
    depth = np.exp(w @ logd) * np.exp(rng.normal(0, 0.45, (n8, n8))).astype(np.float32) * tissue
    lowq = rng.random((n8, n8)) < 0.04                               # a few poor-quality bins
    depth[lowq] *= rng.uniform(0.03, 0.15, int(lowq.sum()))
    lam = depth[..., None] * p * rng.gamma(4.0, 0.25, p.shape).astype(np.float32)
    counts = rng.poisson(lam).astype(np.int32)
    counts[~inc8] = 0
    truth8 = np.where(inc8, frac[..., 1:].argmax(-1) + 1, BG)
    out = raw / "outs"
    write_layer(out, raw, 8, counts, inc8, truth8, ids, names)

    # 16 um = the 8 um bins summed 2 x 2 (Space Ranger aggregates 2 um bins the same way)
    n16 = n8 // 2
    c16 = counts.reshape(n16, 2, n16, 2, -1).sum(axis=(1, 3))
    inc16 = inc8.reshape(n16, 2, n16, 2).any(axis=(1, 3))
    f16 = frac.reshape(n16, 2, n16, 2, -1).sum(axis=(1, 3))
    truth16 = np.where(inc16, f16[..., 1:].argmax(-1) + 1, BG)
    write_layer(out, raw, 16, c16, inc16, truth16, ids, names)
    log(f"[demo] Visium HD-like outs -> {out}  ({time.time() - t0:.0f}s)")


