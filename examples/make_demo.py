#!/usr/bin/env python
r"""Make a small SYNTHETIC demo dataset for Spatial Viewer.

Nothing here comes from a tissue, a patient, an instrument or a sequencing run.
Every pixel and every count is drawn by a seeded random generator from a made-up
layout, so the same --seed always gives the same data. It exists so anyone can try
the whole pipeline (prepare -> export -> viewer) in a few minutes without real data.

    python examples/make_demo.py --out demo/raw

writes

    <out>/README.txt                     says all of this again, next to the files
    <out>/visiumhd/image.tif             4000 x 4000 RGB, H&E-like, 0.32 um/px
    <out>/visiumhd/outs/                 shaped like Space Ranger (Visium HD) output:
        binned_outputs/square_008um/filtered_feature_bc_matrix.h5
        binned_outputs/square_008um/spatial/tissue_positions.parquet
        binned_outputs/square_008um/spatial/scalefactors_json.json
        binned_outputs/square_016um/...  (the 8 um bins summed 2 x 2)
    <out>/visiumhd/truth_square_008um.csv  barcode -> region the bin was drawn from
    <out>/visiumhd/truth_square_016um.csv  (used by tests/smoke_test.py, not by the app)
    <out>/multiplex.ome.tif              2000 x 2000, 9-channel uint16 OME-TIFF, 0.5 um/px
                                         (with the slide-QC cases: a saturated channel, a weaker
                                         duplicate of Synth-Axon, an empty "open" channel, a fold)

The made-up section is a nerve-like cross-section: a lobed tissue outline with an
edge band, loose stroma, five round "fascicles" each wrapped in a "perineurium" rim,
four small "vessels" and one "adipose" patch. Each of those six regions has its own
gene program (about 25 genes up, plus two named marker genes such as MARKER_FASC1),
on top of one shared baseline, with negative-binomial noise. Bins on a boundary mix
the programs of the regions they cover. Sequencing depth varies by region (8 um bins:
median about 100 UMI; adipose and a few percent of random "low quality" bins sit
under 10 UMI), so HVG selection, the whole-section UMAP and Leiden all have real work
to do and their clusters should map back onto the drawn structures.

Gene names are neutral (GENE001 ...) and gene ids are DEMO000001 ...; barcodes use
the Visium HD pattern s_008um_<row>_<col>-1 on a synthetic grid. Every file carries a
"SYNTHETIC" note in its metadata (TIFF description / OME Name, HDF5 attributes,
parquet schema metadata, an extra key in scalefactors_json.json).

Needs only the core requirements (numpy, scipy, tifffile, h5py, pyarrow).
"""
from __future__ import annotations

import argparse
import json
import time
import uuid
from pathlib import Path

import h5py
import numpy as np
import pyarrow as pa
import pyarrow.parquet as pq
import tifffile
from scipy import ndimage, sparse
from scipy.spatial import cKDTree

NOTE = ("SYNTHETIC demo data generated by examples/make_demo.py (Spatial Viewer). "
        "Not derived from any tissue, patient, instrument or sequencing run.")

# ---- layout (micrometres, in a 1280 x 1280 um field) -----------------------------
FIELD_UM = 1280.0
TISSUE_C = (640.0, 660.0)
TISSUE_R = (540.0, 500.0)
EDGE_RHO = 0.88                      # outer 12% of the outline = edge band
FASCICLES = [(430, 470, 130), (790, 450, 115), (600, 820, 150), (900, 760, 95), (300, 760, 75)]
RIM_UM = 25.0                        # perineurium-like rim around each fascicle
VESSELS = [(620, 320, 40), (1020, 560, 35), (720, 620, 35), (200, 560, 30)]
ADIPOSE = [(860, 1000, 75)]

REGIONS = ["background", "stroma", "fascicle", "perineurium", "vessel", "adipose", "edge"]
BG, STROMA, FASC, RIM, VESSEL, FAT, EDGE = range(7)
LUMEN, MEMBRANE = 7, 8               # image-only detail codes (drawn, not separate gene programs)
MARKER_TAG = {STROMA: "STROMA", FASC: "FASC", RIM: "RIM", VESSEL: "VESSEL", FAT: "FAT", EDGE: "EDGE"}

# ---- Visium HD-like image and bins --------------------------------------------------
IMG_PX = 4000
MPP = FIELD_UM / IMG_PX              # 0.32 um per pixel: 8 um bin = 25 px exactly
N_GENES = 300
DEPTH = {STROMA: 110, FASC: 140, RIM: 100, VESSEL: 160, FAT: 30, EDGE: 70}   # median UMI per 8 um bin

# ---- multiplex image ----------------------------------------------------------------
MX_PX = 2000
MX_MPP = 0.5                         # 1 mm field, same layout scaled down
MX_CHANNELS = ["DAPI", "Synth-Membrane", "Synth-Axon", "Synth-Vessel", "Synth-Immune", "Synth-Autofluor",
               # slide-QC cases (protgrid.py): clipped at 65,535 over ~3% of the tissue; the same axons
               # weaker under a dye-tagged name (a duplicate after the name cleanup); an empty channel
               "Synth-Saturated", "Synth-Axon-488", "open-cy5"]
MX_FOLD_UM = 150                     # a fold: every channel bright over a square this wide, in the stroma
# multiplex_tiled.ome.tif: the same image as if stitched from 180 x 150 px camera tiles (edges at
# x = 70 + k*180, y = 40 + k*150), each tile of two markers a little brighter or dimmer, and one of
# them with a per-tile background offset too: the tile-seam correction (protgrid.py / seams.py)
# must find the grid and recover these
MX_TILE = (180, 150, 70, 40)         # w, h, x0, y0 in px
MX_TILED = {"Synth-Membrane": False, "Synth-Autofluor": True}    # name -> also an offset


def log(*a):
    print(*a, flush=True)


def region_at(x, y, detail=False):
    """Region code at points (x, y) in um. `detail` adds vessel lumen for drawing."""
    x = np.asarray(x, np.float32)
    y = np.asarray(y, np.float32)
    dx = (x - TISSUE_C[0]) / TISSUE_R[0]
    dy = (y - TISSUE_C[1]) / TISSUE_R[1]
    th = np.arctan2(dy, dx)
    rho = np.hypot(dx, dy) / (1 + 0.06 * np.sin(3 * th + 1) + 0.04 * np.sin(5 * th + 2))
    inside = rho < 1
    lab = np.zeros(x.shape, np.uint8)
    lab[inside] = STROMA
    lab[inside & (rho >= EDGE_RHO)] = EDGE
    for cx, cy, r in ADIPOSE:
        lab[inside & (np.hypot(x - cx, y - cy) < r)] = FAT
    for cx, cy, r in FASCICLES:
        d = np.hypot(x - cx, y - cy)
        lab[inside & (d < r + RIM_UM)] = RIM
        lab[d < r] = FASC
    for cx, cy, r in VESSELS:
        d = np.hypot(x - cx, y - cy)
        lab[d < r] = VESSEL
        if detail:
            lab[d < 0.68 * r] = LUMEN
    return lab


def _grid(n, step_um, scale=1.0):
    c = ((np.arange(n, dtype=np.float32) + 0.5) * step_um * scale).astype(np.float32)
    return np.meshgrid(c, c)          # X (cols), Y (rows)


def _impulses(rng, lab, step_um, density):
    """Point impulses on a label grid; density[label] = points per um^2."""
    H, W = lab.shape
    dmax = max(density.values())
    n = rng.poisson(H * W * step_um * step_um * dmax)
    ys = rng.integers(0, H, n)
    xs = rng.integers(0, W, n)
    p = np.zeros(int(lab.max()) + 1)
    for k, v in density.items():
        if k < len(p):
            p[k] = v / dmax
    keep = rng.random(n) < p[lab[ys, xs]]
    img = np.zeros((H, W), np.float32)
    np.add.at(img, (ys[keep], xs[keep]), 1.0)
    return img, int(keep.sum())


def _adipose_membranes(lab, step_um, scale, rng):
    """Thin Voronoi walls inside the adipose patch (fat-cell outlines)."""
    out = lab.copy()
    for cx, cy, r in ADIPOSE:
        k = int(np.pi * r * r / 900) + 1                     # ~30 um cells
        a = rng.uniform(0, 2 * np.pi, k)
        rr = r * np.sqrt(rng.uniform(0, 1, k))
        seeds = np.column_stack([cx + rr * np.cos(a), cy + rr * np.sin(a)])
        x0, x1 = int((cx - r) / (step_um * scale)), int((cx + r) / (step_um * scale)) + 2
        y0, y1 = int((cy - r) / (step_um * scale)), int((cy + r) / (step_um * scale)) + 2
        x0, y0 = max(x0, 0), max(y0, 0)
        x1, y1 = min(x1, lab.shape[1]), min(y1, lab.shape[0])
        yy, xx = np.mgrid[y0:y1, x0:x1]
        pts = np.column_stack([(xx.ravel() + 0.5) * step_um * scale, (yy.ravel() + 0.5) * step_um * scale])
        d, _ = cKDTree(seeds).query(pts, k=2)
        wall = ((d[:, 1] - d[:, 0]) < 1.6).reshape(yy.shape)
        sub = out[y0:y1, x0:x1]
        sub[wall & (lab[y0:y1, x0:x1] == FAT)] = MEMBRANE
    return out


