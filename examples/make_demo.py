# H&E-like RGB image
# =====================================================================================
def make_he(rng, path: Path):
    t0 = time.time()
    half = IMG_PX // 2
    X, Y = _grid(half, 2 * MPP)
    lab = region_at(X, Y, detail=True)
    del X, Y
    lab = _adipose_membranes(lab, 2 * MPP, 1.0, rng)
    lab = np.repeat(np.repeat(lab, 2, 0), 2, 1)              # 4000 x 4000

    #               background       stroma          fascicle        perineurium
    colors = np.array([[244, 241, 243], [234, 158, 196], [240, 192, 216], [206, 122, 178],
                       # vessel wall      adipose          edge            lumen           fat membrane
                       [214, 92, 142], [249, 245, 247], [226, 140, 186], [247, 222, 230], [222, 150, 188]],
                      np.float32)
    hema = np.array([92, 52, 140], np.float32)               # nuclei

    # streaky collagen texture and wavy fibres
    fib = ndimage.gaussian_filter(rng.standard_normal((IMG_PX, IMG_PX), dtype=np.float32), (1.2, 7.0))
    fib /= fib.std() + 1e-6
    tex = np.where(np.isin(lab, (STROMA, EDGE, RIM)), 0.05, 0.025).astype(np.float32) * fib
    tex[np.isin(lab, (BG, FAT, LUMEN))] = 0
    del fib

    density = {STROMA: 0.007, FASC: 0.016, RIM: 0.03, VESSEL: 0.025, EDGE: 0.014, MEMBRANE: 0.004}
    imp, n = _impulses(rng, lab, MPP, density)
    nuc = ndimage.gaussian_filter(imp, (2.2, 4.0)) * (2 * np.pi * 2.2 * 4.0) * 1.4
    del imp
    # red blood cells in the vessel lumens
    rbc, _ = _impulses(rng, lab, MPP, {LUMEN: 0.01})
    rbc = np.clip(ndimage.gaussian_filter(rbc, 3.0) * (2 * np.pi * 9) * 1.2, 0, 1)
    np.clip(nuc, 0, 1, out=nuc)
    log(f"[demo] H&E: {n:,} nuclei")

    rgb = np.empty((IMG_PX, IMG_PX, 3), np.uint8)
    blood = np.array([200, 50, 70], np.float32)
    for c in range(3):
        ch = colors[:, c][lab] * (1.0 + tex)
        ch = ch * (1 - nuc) + hema[c] * nuc
        ch = ch * (1 - rbc) + blood[c] * rbc
        ch = ndimage.gaussian_filter(ch, 0.8)
        ch += rng.normal(0, 2.5, ch.shape).astype(np.float32)
        rgb[..., c] = np.clip(ch, 0, 255).astype(np.uint8)
    path.parent.mkdir(parents=True, exist_ok=True)
    tifffile.imwrite(str(path), rgb, photometric="rgb", tile=(512, 512), compression="zlib",
                     resolution=(1e4 / MPP, 1e4 / MPP), resolutionunit="CENTIMETER",
                     metadata=None, description=NOTE, software="make_demo.py (synthetic)")
    log(f"[demo] {path}  {IMG_PX}x{IMG_PX} RGB, {MPP:g} um/px  ({time.time() - t0:.0f}s)")


